from pathlib import Path
from PIL import Image
import shutil

root = Path(__file__).resolve().parents[1]
source = root / 'server/uploads'
widths = (200, 560, 1200)
manifest = []
original_bytes = optimized_bytes = 0
for path in sorted(source.glob('*.webp')):
    image = Image.open(path)
    manifest.append('/uploads/' + path.name)
    for width in widths:
        output = source / 'optimized' / f'{path.stem}-{width}.webp'
        output.parent.mkdir(parents=True, exist_ok=True)
        resized = image.copy()
        resized.thumbnail((width, width), Image.Resampling.LANCZOS)
        resized.save(output, 'WEBP', quality=82, method=6)
        public = root / 'public/uploads/optimized' / output.name
        public.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(output, public)
        if width == 560:
            original_bytes += path.stat().st_size
            optimized_bytes += output.stat().st_size
(root / 'src/lib/imageVariants.ts').write_text(
    '// Generated by scripts/optimize-images.py. Unknown uploads use their original URL.\n'
    + 'export const OPTIMIZED_IMAGES = new Set(' + repr(manifest) + ');\n', encoding='utf-8')
print(f'{len(manifest)} photos: original {original_bytes:,} bytes; 560px cards {optimized_bytes:,} bytes; reduction {100*(1-optimized_bytes/original_bytes):.1f}%')
